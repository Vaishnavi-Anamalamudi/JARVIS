package com.adaptivegateway.config;

import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.security.SecurityScheme;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class OpenApiConfig {

    @Bean
    public OpenAPI adaptiveGatewayOpenApi(ApplicationProperties properties) {
        return new OpenAPI()
                .components(new Components()
                        .addSecuritySchemes("bearerAuth", new SecurityScheme()
                                .type(SecurityScheme.Type.HTTP)
                                .scheme("bearer")
                                .bearerFormat("JWT")))
                .info(new Info()
                        .title("Adaptive API Gateway API")
                        .version(properties.apiVersion())
                        .description("Backend API for the Adaptive API Gateway with Traffic-Aware Rate Limiting")
                        .contact(new Contact().name("Adaptive Gateway Engineering"))
                        .license(new License().name("Apache-2.0")));
    }
}
